fn schema_value<T: JsonSchema>() -> Value {
    serde_json::to_value(schema_for!(T)).expect("schema serializes")
}

fn response_schema_value<T: JsonSchema>() -> Value {
    let mut schema = schema_value::<ProtocolResponse<T>>();
    if let Some(object) = schema.as_object_mut() {
        object.insert(
            "oneOf".to_string(),
            serde_json::json!([
                {"required": ["result"], "not": {"required": ["error"]}},
                {"required": ["error"], "not": {"required": ["result"]}}
            ]),
        );
    }
    schema
}
